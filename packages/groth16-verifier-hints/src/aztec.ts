/** Optional Aztec v6 integration. Inject the application's existing SDK classes;
 * this module neither loads a second backend nor submits transactions. */
import {assertPreparedRequest, parseProfile, type PreparedRequest} from './current.js';

export interface FieldLike { toBigInt(): bigint }
export interface AddressLike { toField(): FieldLike }
export interface AztecTypes<F extends FieldLike, A extends AddressLike, C> {
  readonly Fr: new (value: bigint) => F;
  readonly AztecAddress: {readonly ZERO: A};
  readonly Capsule: new (contractAddress: A, storageSlot: F, data: F[], scope?: A) => C;
}
export interface CapsuleInteraction<C, I> { with(options: {capsules: C[]}): I }
export interface GeneratedContract<A extends AddressLike, C, I> {
  readonly address: A;
  readonly methods: {verify(...args: any[]): I & CapsuleInteraction<C,I>};
}
/** Attach untrusted witnesses to precisely the address bound into the statement.
 * Return a normal SDK interaction; the application chooses simulate/prove/send.
 * The generated contract independently checks chain, version and its address.
 */
export function preparePrivateCall<F extends FieldLike,A extends AddressLike,C,I>(
  profile: unknown, packet: PreparedRequest, contract: GeneratedContract<A,C,I>, sdk: AztecTypes<F,A,C>,
): I {
  const p=parseProfile(profile);
  assertPreparedRequest(p,packet);
  if(p.mode==='offchain') throw new Error('Offchain profile requires a producer proof');
  if(contract.address.toField().toBigInt()!==packet.application[2]) throw new Error('Contract/application address mismatch');
  const capsules=packet.capsules.map(c=> {
    if(c.scope!==0n) throw new Error('Generated consumers require capsule scope zero');
    return new sdk.Capsule(contract.address,new sdk.Fr(c.slot),c.values.map(v=>new sdk.Fr(v)),sdk.AztecAddress.ZERO);
  });
  // ABI order is generated by groth16.scaffold. Noir arrays of Field and
  // u128 accept BigInt values directly through the pinned SDK ABI encoder.
  const a=packet.callArguments;
  const common=[a.statement,a.application,...(p.inputCount===0?[]:[a.public_inputs])];
  const args=p.keyPolicy==='fixed' ? [...common,a.raw] : [...common,a.key,a.proof];
  return contract.methods.verify(...args).with({capsules});
}

import {assertProducerCertificate, type ProducerCertificate} from './producer.js';
/** Prepare the O consumer call after local producer-proof verification. The
 * contract's immutable producer-key policy remains the authorization boundary. */
export function prepareOffchainCall<A extends AddressLike,C,I>(
  profile:unknown,packet:PreparedRequest,certificate:ProducerCertificate,
  contract:GeneratedContract<A,C,I>,approvedProducerKeyHash:bigint,
):I & CapsuleInteraction<C,I> {
  const p=parseProfile(profile);
  if(p.mode!=='offchain')throw new Error('Expected offchain profile');
  assertProducerCertificate(p,packet,certificate);
  if(certificate.producerKeyHash!==approvedProducerKeyHash)throw new Error('Unapproved producer key');
  if(contract.address.toField().toBigInt()!==packet.application[2])throw new Error('Contract/application address mismatch');
  return contract.methods.verify(packet.statement,packet.application,...(p.inputCount===0?[]:[packet.publicInputs]),certificate.producerKey,certificate.proof);
}
