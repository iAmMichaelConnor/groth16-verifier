#!/usr/bin/env python3
"""Generate the fixed-key provider of the Circom multiplier key for the tests.

Reuse generic preprocessing and offsets. No setup or proof is created.
--check compares the existing fixture without writing it.
"""

from __future__ import annotations
import argparse
import json
from pathlib import Path
import re
import sys
import tempfile

LIB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(LIB / "packages/groth16-verifier-hints/python"))
sys.path.insert(0, str(LIB / "scripts"))
from groth16 import _offsets, _preprocess as g  # noqa: E402
from noir_format import format_noir  # noqa: E402

MULTIPLIER_VK = LIB / "fixtures/multiplier/verification_key.json"
DESTINATION = LIB / "tests/fixed_multiplier_vector/src/key1.nr"
SELF = "scripts/generate_test_keys.py"
PROVIDER_IMPORTS = """use groth16::provider::{
    VerifyingKey, FixedKey, Half, Fp, Fp2, Fp6, Fp12, G1Affine, G2Affine, LineEvaluation,
    LineScheduleRaw, BigNum,
};
"""


def _emit(key: dict, name: str) -> str:
    """Provider source as packages/groth16-verifier-hints/python/groth16/generate.py emits it, before imports."""
    with tempfile.TemporaryDirectory() as temp:
        vk, out = Path(temp) / "key.json", Path(temp) / "provider.nr"
        vk.write_text(json.dumps(key))
        record = g.generate(vk, name, out)
        source = out.read_text()
    correction = (
        None
        if record["biasCorrection"] is None
        else tuple(map(int, record["biasCorrection"]))
    )
    extra, _ = _offsets.methods(correction, record["nPublic"])
    marker = " fn gamma_lines()->LineScheduleRaw"
    g.require(source.count(marker) == 1, "Unexpected provider emission format")
    return source.replace(marker, extra + marker)


def output() -> str:
    key = json.loads(MULTIPLIER_VK.read_text())
    source = _emit(key, "Key1")
    source = re.sub(r"^use [^;]+;\n", "", source, flags=re.M)
    source = source.replace(
        "// Generated trusted code. Change key through regeneration and a new compiled verifier.\n",
        "",
    )
    return (
        "// TEST ONLY. Do not use this provider to authorise anything in an application.\n"
        f"// Generated by {SELF}; do not edit.\n"
        "// Key: the Circom multiplier fixture (fixtures/multiplier). Its trusted\n"
        "// setup is a local development setup; the relation product = a*b proves nothing.\n"
        + PROVIDER_IMPORTS
        + source
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    (text,) = format_noir([output()])
    if args.check:
        if not DESTINATION.is_file() or DESTINATION.read_text() != text:
            print(f"{DESTINATION.relative_to(LIB)}: out of date", file=sys.stderr)
            return 1
        return 0
    DESTINATION.parent.mkdir(parents=True, exist_ok=True)
    DESTINATION.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
